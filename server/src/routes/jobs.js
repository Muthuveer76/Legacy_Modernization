import { Router } from 'express';
import mongoose from 'mongoose';
import { z } from 'zod';
import { config } from '../config.js';
import { requireAuth } from '../middleware/auth.js';
import { HttpError, parseBody } from '../middleware/errors.js';
import { Job } from '../models/Job.js';
import { deleteAssetsFor, loadAssets } from '../models/JobAsset.js';
import { Project } from '../models/Project.js';
import { cancelJob, isActive, revalidateJob } from '../pipeline/runner.js';
import { buildReport, fileSlug, zipJob } from '../services/exporter.js';
import { createJob } from './projects.js';

const router = Router();
router.use(requireAuth);

const REVIEWABLE = ['review', 'approved', 'rejected'];

async function loadJob(req, select) {
  if (!mongoose.isValidObjectId(req.params.id)) throw new HttpError(404, 'Job not found');
  const query = Job.findOne({ _id: req.params.id, owner: req.user.id });
  if (select) query.select(select);
  const job = await query;
  if (!job) throw new HttpError(404, 'Job not found');
  return job;
}

function assertReviewable(job) {
  if (job.status === 'merged') throw new HttpError(409, 'This job is already merged into the project codebase');
  if (!REVIEWABLE.includes(job.status)) throw new HttpError(409, `Job is ${job.status}; it can be reviewed once the pipeline has finished`);
}

function jobView(job, project) {
  const o = job.toObject({ virtuals: false });
  return {
    id: o._id.toString(),
    number: o.number,
    status: o.status,
    engine: o.engine,
    target: o.target,
    feedback: o.feedback || null,
    parentJob: o.parentJob || null,
    stages: o.stages,
    progress: o.progress,
    error: o.error?.message ? o.error : null,
    parse: o.parse || null,
    analysis: o.analysis || null,
    generation: o.generation?.files?.length ? o.generation : null,
    validation: o.validation || null,
    baselineValidation: o.baselineValidation || null,
    review: o.review,
    mergedAt: o.mergedAt || null,
    createdAt: o.createdAt,
    startedAt: o.startedAt,
    finishedAt: o.finishedAt,
    project: project ? { id: project._id.toString(), name: project.name, target: project.target, mergedJobId: project.merged?.jobId?.toString() || null } : null,
    aiEnabled: config.ai.enabled,
  };
}

router.get('/:id', async (req, res) => {
  const job = await loadJob(req);
  const project = await Project.findById(job.project).select('name target merged.jobId');
  res.json({ job: jobView(job, project) });
});

router.get('/:id/status', async (req, res) => {
  const job = await loadJob(req, 'status stages progress error validation.score number');
  res.json({ status: job.status, stages: job.stages, progress: job.progress, error: job.error?.message ? job.error : null, score: job.validation?.score ?? null });
});

router.get('/:id/ast', async (req, res) => {
  const job = await loadJob(req, '_id');
  const asts = (await loadAssets(job._id, 'ast')).map((a) => a.data);
  const file = req.query.file ? String(req.query.file) : asts[0]?.file;
  const ast = asts.find((a) => a.file === file);
  if (!ast) throw new HttpError(404, 'No syntax tree for that file');
  res.json({ files: asts.map((a) => a.file), ast });
});

router.get('/:id/sources', async (req, res) => {
  const job = await loadJob(req, '_id');
  res.json({ sources: (await loadAssets(job._id, 'source')).map((a) => a.data) });
});

router.get('/:id/baseline', async (req, res) => {
  const job = await loadJob(req, 'baselineValidation');
  const [baseline] = await loadAssets(job._id, 'baseline');
  if (!baseline) throw new HttpError(404, 'This job has no separate rule-based baseline (it was generated by the rule-based translator)');
  res.json({ baseline: baseline.data, validation: job.baselineValidation });
});

router.post('/:id/cancel', async (req, res) => {
  const job = await loadJob(req, 'status');
  if (!['queued', 'running'].includes(job.status)) throw new HttpError(409, `Job is already ${job.status}`);
  const result = cancelJob(job._id);
  if (result === 'dequeued' || !result) {
    await Job.updateOne({ _id: job._id }, { $set: { status: 'cancelled', error: { message: 'Job was cancelled.' }, finishedAt: new Date() } });
  }
  res.json({ ok: true });
});

router.delete('/:id', async (req, res) => {
  const job = await loadJob(req, 'status project');
  if (isActive(job._id) || ['queued', 'running'].includes(job.status)) throw new HttpError(409, 'Cancel the job before deleting it');
  const project = await Project.findById(job.project).select('merged.jobId lastJob.id');
  if (project?.merged?.jobId?.equals(job._id)) throw new HttpError(409, 'This job is merged into the project codebase and cannot be deleted');
  await job.deleteOne();
  await deleteAssetsFor([job._id]);
  if (project?.lastJob?.id?.equals(job._id)) {
    const latest = await Job.findOne({ project: job.project }).sort({ number: -1 }).select('number status validation.score engine.used finishedAt');
    await Project.updateOne({ _id: job.project }, { $set: { lastJob: latest ? { id: latest._id, number: latest.number, status: latest.status, score: latest.validation?.score ?? null, engine: latest.engine?.used, at: latest.finishedAt } : {} } });
  }
  res.json({ ok: true });
});

const FileUpdateSchema = z
  .object({
    path: z.string().min(1),
    content: z.string().max(2_000_000).optional(),
    status: z.enum(['pending', 'accepted', 'rejected']).optional(),
  })
  .refine((b) => b.content !== undefined || b.status !== undefined, { message: 'Provide content or status' });

router.patch('/:id/files', async (req, res) => {
  const job = await loadJob(req);
  assertReviewable(job);
  if (job.status !== 'review') throw new HttpError(409, 'Reopen the review (it is already decided) before editing files');
  const body = parseBody(FileUpdateSchema, req.body);
  const file = job.generation.files.find((f) => f.path === body.path);
  if (!file) throw new HttpError(404, 'File not found in this job');
  if (body.content !== undefined) file.content = body.content;
  if (body.status) file.status = body.status;
  await job.save();
  res.json({ file: { path: file.path, status: file.status, edited: file.content !== file.original, content: file.content } });
});

router.post('/:id/revalidate', async (req, res) => {
  const job = await loadJob(req);
  assertReviewable(job);
  const validation = await revalidateJob(job);
  job.validation = validation;
  await job.save();
  await Project.updateOne({ _id: job.project, 'lastJob.id': job._id }, { $set: { 'lastJob.score': validation.score } });
  res.json({ validation });
});

const CommentSchema = z.object({
  file: z.string().max(300).optional().nullable(),
  line: z.number().int().positive().optional().nullable(),
  body: z.string().trim().min(1, 'Comment cannot be empty').max(4000),
});

router.post('/:id/comments', async (req, res) => {
  const job = await loadJob(req);
  assertReviewable(job);
  const body = parseBody(CommentSchema, req.body);
  job.review.comments.push({ file: body.file || null, line: body.line || null, body: body.body, author: { id: req.user.id, name: req.user.name } });
  await job.save();
  res.status(201).json({ comments: job.review.comments });
});

router.patch('/:id/comments/:commentId', async (req, res) => {
  const job = await loadJob(req);
  const comment = job.review.comments.id(req.params.commentId);
  if (!comment) throw new HttpError(404, 'Comment not found');
  const { resolved } = parseBody(z.object({ resolved: z.boolean() }), req.body);
  comment.resolved = resolved;
  await job.save();
  res.json({ comments: job.review.comments });
});

router.delete('/:id/comments/:commentId', async (req, res) => {
  const job = await loadJob(req);
  const comment = job.review.comments.id(req.params.commentId);
  if (!comment) throw new HttpError(404, 'Comment not found');
  comment.deleteOne();
  await job.save();
  res.json({ comments: job.review.comments });
});

const ReviewSchema = z.object({
  decision: z.enum(['approved', 'rejected', 'changes-requested', 'reopen']),
  summary: z.string().trim().max(4000).optional().default(''),
});

router.post('/:id/review', async (req, res) => {
  const job = await loadJob(req);
  assertReviewable(job);
  const { decision, summary } = parseBody(ReviewSchema, req.body);
  if (decision === 'reopen') {
    if (job.status === 'merged') throw new HttpError(409, 'Merged jobs cannot be reopened');
    job.status = 'review';
    job.review.decision = null;
    await job.save();
    await Project.updateOne({ _id: job.project, 'lastJob.id': job._id }, { $set: { 'lastJob.status': 'review' } });
    return res.json({ job: jobView(job) });
  }
  if (job.status !== 'review') throw new HttpError(409, `Job was already ${job.status}; reopen it to change the decision`);
  const reviewer = { id: req.user.id, name: req.user.name };
  let newJob = null;
  if (decision === 'approved') {
    const kept = job.generation.files.filter((f) => f.status !== 'rejected');
    if (!kept.length) throw new HttpError(400, 'Every file is rejected; there is nothing to approve');
    for (const f of job.generation.files) if (f.status === 'pending') f.status = 'accepted';
    job.status = 'approved';
  } else if (decision === 'rejected') {
    job.status = 'rejected';
  } else {
    const open = job.review.comments.filter((c) => !c.resolved);
    const feedback = [summary, ...open.map((c) => `- ${c.file ? `${c.file}${c.line ? `:${c.line}` : ''}: ` : ''}${c.body}`)].filter(Boolean).join('\n');
    if (!feedback) throw new HttpError(400, 'Describe the changes you want (summary or unresolved comments)');
    const project = await Project.findById(job.project);
    newJob = await createJob({ project, userId: req.user.id, engine: job.engine.used === 'claude' ? 'claude' : 'auto', feedback, parentJob: job._id });
    job.status = 'rejected';
  }
  job.review.decision = decision;
  job.review.summary = summary;
  job.review.decidedAt = new Date();
  job.review.decidedBy = reviewer;
  await job.save();
  await Project.updateOne({ _id: job.project, 'lastJob.id': job._id }, { $set: { 'lastJob.status': job.status } });
  res.json({ job: jobView(job), newJob: newJob ? newJob.summary() : null });
});

router.post('/:id/merge', async (req, res) => {
  const job = await loadJob(req);
  if (job.status !== 'approved') throw new HttpError(409, 'Only approved jobs can be merged');
  const files = job.generation.files.filter((f) => f.status !== 'rejected').map((f) => ({ path: f.path, language: f.language, kind: f.kind, content: f.content }));
  const mergedAt = new Date();
  await Project.updateOne({ _id: job.project }, { $set: { merged: { jobId: job._id, jobNumber: job.number, mergedAt, files }, 'lastJob.status': 'merged' } });
  job.status = 'merged';
  job.mergedAt = mergedAt;
  await job.save();
  res.json({ job: jobView(job), merged: { jobId: job._id, jobNumber: job.number, mergedAt, fileCount: files.length } });
});

router.get('/:id/report', async (req, res) => {
  const job = await loadJob(req);
  const project = await Project.findById(job.project);
  res.setHeader('Content-Disposition', `inline; filename="${fileSlug(project.name)}-job-${job.number}-report.md"`);
  res.type('text/markdown').send(buildReport(project, job));
});

router.get('/:id/export', async (req, res) => {
  const job = await loadJob(req);
  if (!job.generation?.files?.length) throw new HttpError(409, 'This job has not generated any code yet');
  const project = await Project.findById(job.project);
  const buffer = await zipJob(project, job);
  res.setHeader('Content-Type', 'application/zip');
  res.setHeader('Content-Disposition', `attachment; filename="${fileSlug(project.name)}-job-${job.number}.zip"`);
  res.send(buffer);
});

export default router;
